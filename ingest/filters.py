import os

SKIP_DIRS = {
    ".git", "node_modules", "dist", "build", "vendor", "venv", ".venv","__pycache__", ".idea", ".vscode", "site-packages", "target",
}
SKIP_SUFFIXES = (".min.js", ".min.css", ".map")
SKIP_FILENAMES = {"package-lock.json", "yarn.lock", "poetry.lock"}
MAX_FILE_BYTES = 500_000
MAX_AVG_LINE_LEN = 200

def should_skip_dir(dir_name):
    return dir_name in SKIP_DIRS

def skip_reason(file_path):
    """Cheap checks using only the filename and size. Returns a reason string, or None to keep."""
    name = os.path.basename(file_path)
    if name in SKIP_FILENAMES:
        return "lockfile"
    if name.endswith(SKIP_SUFFIXES):
        return "minified/generated by name"
    try:
        size = os.path.getsize(file_path)
    except OSError:
        return "unreadable"
    if size > MAX_FILE_BYTES:
        return f"too large ({size} bytes)"
    return None

def looks_minified(source: bytes):
    """Content check: minified code has very long lines because newlines are stripped."""
    if len(source) < 1000:
        return False
    line_count = source.count(b"\n") + 1
    return len(source) / line_count > MAX_AVG_LINE_LEN