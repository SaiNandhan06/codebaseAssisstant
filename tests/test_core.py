class TestFilters:
    """Test ingest/filters.py noise filtering."""

    def test_should_skip_git(self):
        from ingest.filters import should_skip_dir
        assert should_skip_dir(".git") is True
        assert should_skip_dir("node_modules") is True
        assert should_skip_dir("venv") is True
        assert should_skip_dir("src") is False
        assert should_skip_dir("lib") is False

    def test_skip_reason_lockfile(self):
        from ingest.filters import skip_reason
        # Create a temporary lockfile to test
        import tempfile
        with tempfile.NamedTemporaryFile(suffix="package-lock.json", delete=False) as f:
            f.write(b"{}")
            tmp = f.name
        # Rename to match exact filename
        lock_path = os.path.join(os.path.dirname(tmp), "package-lock.json")
        os.rename(tmp, lock_path)
        try:
            assert skip_reason(lock_path) == "lockfile"
        finally:
            os.remove(lock_path)

    def test_skip_reason_minified(self):
        from ingest.filters import skip_reason
        import tempfile
        with tempfile.NamedTemporaryFile(suffix=".min.js", delete=False) as f:
            f.write(b"var x=1;")
            tmp = f.name
        try:
            assert skip_reason(tmp) == "minified/generated by name"
        finally:
            os.remove(tmp)

    def test_looks_minified(self):
        from ingest.filters import looks_minified
        # Normal code
        normal = b"def foo():\n    return 1\n" * 50
        assert looks_minified(normal) is False
        # Minified code (one very long line)
        minified = b"a" * 50000 + b"\n"
        assert looks_minified(minified) is True
        # Short file (under 1000 bytes) should not trigger
        short = b"a" * 999
        assert looks_minified(short) is False


class TestParser:
    """Test ingest/parse.py class/method extraction."""

    def test_parse_sample_class(self):
        from ingest.parse import parse_file
        sample_path = os.path.join(
            os.path.dirname(os.path.dirname(__file__)),
            "samples", "sample_class.py"
        )
        with open(sample_path, "rb") as f:
            source = f.read()

        chunks = parse_file(source, "samples/sample_class.py", ".py")

        assert len(chunks) == 5

        kinds = {c.kind for c in chunks}
        assert kinds == {"class", "method", "function"}

        names = {c.name for c in chunks}
        assert "ShoppingCart" in names
        assert "__init__" in names
        assert "add_item" in names
        assert "total" in names
        assert "standalone_helper" in names

        # Check parent linkage
        methods = [c for c in chunks if c.kind == "method"]
        for m in methods:
            assert m.parent == "ShoppingCart"

        # Check that standalone_helper has no parent
        func = [c for c in chunks if c.name == "standalone_helper"][0]
        assert func.parent is None

    def test_chunk_id_format(self):
        from ingest.parse import parse_file
        source = b"def greet(name):\n    return f'Hello {name}'\n"
        chunks = parse_file(source, "test.py", ".py")
        assert len(chunks) == 1
        assert chunks[0].id == "test.py::greet:1"

    def test_javascript_parsing(self):
        from ingest.parse import parse_file, LANGUAGES
        if ".js" not in LANGUAGES:
            pytest.skip("JavaScript parser not available")
        source = b"""
function hello() {
    console.log("hello");
}

class Greeter {
    greet(name) {
        return "Hello " + name;
    }
}
"""
        chunks = parse_file(source, "test.js", ".js")
        names = {c.name for c in chunks}
        assert "hello" in names
        assert "Greeter" in names
        assert "greet" in names


class TestTokenizer:
    """Test index/text.py sub-word tokenizer."""

    def test_camel_case_split(self):
        from index.text import tokenize
        tokens = tokenize("calculateTotal")
        assert "calculate" in tokens
        assert "total" in tokens

    def test_snake_case_split(self):
        from index.text import tokenize
        tokens = tokenize("get_user_name")
        assert "get" in tokens
        assert "user" in tokens
        assert "name" in tokens

    def test_mixed(self):
        from index.text import tokenize
        tokens = tokenize("getUserName get_user_name")
        assert "get" in tokens
        assert "user" in tokens
        assert "name" in tokens

    def test_context_header(self):
        from ingest.parse import Chunk
        from index.text import context_header
        chunk = Chunk(
            id="test.py::MyClass.my_method:10",
            file_path="test.py",
            language="python",
            kind="method",
            name="my_method",
            parent="MyClass",
            start_line=10,
            end_line=20,
            code="def my_method(self): pass",
        )
        header = context_header(chunk)
        assert "python" in header
        assert "MyClass" in header
        assert "my_method" in header
        assert "test.py" in header


class TestRRF:
    """Test Reciprocal Rank Fusion logic."""

    def test_rrf_basic(self):
        """Test RRF score computation for a simple case."""
        k = 60
        # Simulate: doc at rank 0 in both systems should have highest RRF
        scores = {}
        for doc_id in range(4):
            bm25_rank = doc_id
            dense_rank = doc_id
            score = 1.0 / (k + bm25_rank) + 1.0 / (k + dense_rank)
            scores[doc_id] = score

        # Doc 0 should have the highest score
        assert scores[0] > scores[1] > scores[2] > scores[3]

        # Expected score for rank 0: 2/(60+0) = 2/60 ≈ 0.0333
        assert abs(scores[0] - 2.0/60) < 0.0001

    def test_rrf_different_ranks(self):
        """Test when BM25 and dense disagree."""
        k = 60
        # Doc 0: BM25 rank 0, dense rank 3
        # Doc 1: BM25 rank 3, dense rank 0
        doc0 = 1.0/(k+0) + 1.0/(k+3)
        doc1 = 1.0/(k+3) + 1.0/(k+0)
        # Should be equal since both have one rank-0 and one rank-3
        assert abs(doc0 - doc1) < 0.0001


