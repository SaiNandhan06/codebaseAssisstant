class TestChunkSplitting:
    """Test oversized chunk splitting."""

    def test_split_oversized(self):
        from ingest.pipeline import _split_oversized
        from ingest.parse import Chunk
        # Create a chunk with very long code
        long_code = "x = 1\n" * 2000  # ~12000 chars
        chunk = Chunk(
            id="test.py::big_func:1",
            file_path="test.py",
            language="python",
            kind="function",
            name="big_func",
            parent=None,
            start_line=1,
            end_line=2000,
            code=long_code,
        )
        pieces = _split_oversized(chunk, max_chars=6000)
        assert len(pieces) > 1
        assert all("part" in p.name for p in pieces)

    def test_no_split_small(self):
        from ingest.pipeline import _split_oversized
        from ingest.parse import Chunk
        chunk = Chunk(
            id="test.py::small:1",
            file_path="test.py",
            language="python",
            kind="function",
            name="small",
            parent=None,
            start_line=1,
            end_line=5,
            code="def small(): pass",
        )
        pieces = _split_oversized(chunk)
        assert len(pieces) == 1
        assert pieces[0].name == "small"


